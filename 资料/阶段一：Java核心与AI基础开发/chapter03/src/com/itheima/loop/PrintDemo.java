package com.itheima.loop;

public class PrintDemo {
    /*
        张三123
        李四456

        print() : 打印数据后, 没有换行
        println() : 打印数据后, 有换行效果
     */
    public static void main(String[] args) {
        System.out.print("张三");
        System.out.println("123");
        System.out.print("李四");
        System.out.println("456");
    }
}
