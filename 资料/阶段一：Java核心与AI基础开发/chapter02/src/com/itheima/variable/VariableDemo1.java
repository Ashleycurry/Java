public class VariableDemo1 {
    /*
        变量介绍: 是内存中的一块存储空间, 可以理解为是一个盒子, 用来存储程序中经常发送改变的数据

        变量的定义格式: 数据类型 变量名称 = 数据值;

        数据类型: int(整数)
     */
    public static void main(String[] args) {
        int age = 18;
        System.out.println(age);

        age = 19;
        System.out.println(age);

        int salary = 12000;
        System.out.println(salary);
    }
}
