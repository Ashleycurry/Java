package com.myproject.operator;

public class OperatorDemo03 {
    public static void main(String[] args) {
        // 自增自减运算符
        int a = 10;
        a++;
        System.out.println(a);
        ++a;
        System.out.println(a);

        int b = 10;
        b--;
        System.out.println(a);
        --b;
        System.out.println(b);


    }
}
